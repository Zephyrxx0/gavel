export function formatComparisonMarkdown(data: Comparison, labelA?: string, labelB?: string): string {
  const nameA = labelA || 'Document A';
  const nameB = labelB || 'Document B';
  const sections: string[] = [STATUTORY_DISCLAIMER_HEADER, ''];

  sections.push(`# Document Comparison Dossier: ${nameA} vs ${nameB}`);
  sections.push(`**Overall Favorability:** ${data.favorabilityVerdict.toUpperCase()}`);
  sections.push(`**Verdict Rationale:** ${data.verdictRationale}`);
  sections.push('');

  sections.push('## Comparative Metrics');
  sections.push(`- Clauses Favoring ${nameA}: ${data.favorabilityMetrics.clausesFavoringDocA}`);
  sections.push(`- Clauses Favoring ${nameB}: ${data.favorabilityMetrics.clausesFavoringDocB}`);
  sections.push(`- Critical Inconsistencies: ${data.favorabilityMetrics.criticalInconsistencies}`);
  sections.push('');

  if (data.inconsistencies?.length > 0) {
    sections.push('## Inconsistencies & Contradictions');
    for (const inc of data.inconsistencies) {
      sections.push(`### [${inc.severity.toUpperCase()}] ${inc.clauseTitle}`);
      sections.push(inc.description);
      sections.push('');
    }
  }

  sections.push('## Side-by-Side Differences');
  for (const diff of data.clauseDifferences) {
    const favorLabel = diff.favors === 'docA' ? nameA : diff.favors === 'docB' ? nameB : 'Neutral';
    sections.push(`### ${diff.category} (Risk: ${diff.riskRating.toUpperCase()} | Favors: ${favorLabel})`);
    sections.push(`**Analysis:** ${diff.notes}`);
    sections.push(`**${nameA}:**`);
    sections.push('```');
    sections.push(diff.textDocA);
    sections.push('```');
    sections.push(`**${nameB}:**`);
    sections.push('```');
    sections.push(diff.textDocB);
    sections.push('```');
    sections.push('');
  }

  sections.push('## Negotiation Guide');
  sections.push(`**Overall Recommendation:** ${data.negotiationGuide.recommendation}`);
  sections.push('');

  sections.push('### Push Back On');
  if (data.negotiationGuide.pushBack.length === 0) sections.push('_None_');
  for (const item of data.negotiationGuide.pushBack) {
    sections.push(`#### ${item.clauseTitle}`);
    sections.push(`*Rationale:* ${item.rationale}`);
    if (item.suggestedAlternative) {
      sections.push(`*Suggested Alternative:* "${item.suggestedAlternative}"`);
    }
    sections.push('');
  }

  sections.push('### Accept As-Is');
  if (data.negotiationGuide.acceptAsIs.length === 0) sections.push('_None_');
  for (const item of data.negotiationGuide.acceptAsIs) {
    sections.push(`#### ${item.clauseTitle}`);
    sections.push(`*Rationale:* ${item.rationale}`);
    sections.push('');
  }

  sections.push('### Flag for Lawyer Review');
  if (data.negotiationGuide.flagForLawyer.length === 0) sections.push('_None_');
  for (const item of data.negotiationGuide.flagForLawyer) {
    sections.push(`#### ${item.clauseTitle}`);
    sections.push(`*Rationale:* ${item.rationale}`);
    if (item.suggestedAlternative) {
      sections.push(`*Suggested Counter-Language:* "${item.suggestedAlternative}"`);
    }
    sections.push('');
  }

  return sections.join('\n');
}

export function formatComparisonPlainText(data: Comparison, labelA?: string, labelB?: string): string {
  const nameA = labelA || 'Document A';
  const nameB = labelB || 'Document B';
  const sections: string[] = [STATUTORY_DISCLAIMER_HEADER, ''];

  sections.push(`DOCUMENT COMPARISON DOSSIER: ${nameA.toUpperCase()} VS ${nameB.toUpperCase()}`);
  sections.push(`Overall Verdict: ${data.favorabilityVerdict.toUpperCase()}`);
  sections.push(`Verdict Rationale: ${data.verdictRationale}`);
  sections.push('==========================================================================');
  sections.push('');

  sections.push('METRICS:');
  sections.push(`* Favoring ${nameA}: ${data.favorabilityMetrics.clausesFavoringDocA}`);
  sections.push(`* Favoring ${nameB}: ${data.favorabilityMetrics.clausesFavoringDocB}`);
  sections.push(`* Critical Inconsistencies: ${data.favorabilityMetrics.criticalInconsistencies}`);
  sections.push('');

  if (data.inconsistencies?.length > 0) {
    sections.push('INCONSISTENCIES:');
    sections.push('--------------------------------------------------------------------------');
    for (const inc of data.inconsistencies) {
      sections.push(`[${inc.severity.toUpperCase()}] ${inc.clauseTitle}: ${inc.description}`);
    }
    sections.push('');
  }

  sections.push('DIFFERENCES:');
  sections.push('--------------------------------------------------------------------------');
  for (const diff of data.clauseDifferences) {
    const favorLabel = diff.favors === 'docA' ? nameA : diff.favors === 'docB' ? nameB : 'Neutral';
    sections.push(`[${diff.category}] Risk: ${diff.riskRating.toUpperCase()} | Favors: ${favorLabel}`);
    sections.push(`Notes: ${diff.notes}`);
    sections.push(`${nameA}: "${diff.textDocA.trim()}"`);
    sections.push(`${nameB}: "${diff.textDocB.trim()}"`);
    sections.push('');
  }

  sections.push('NEGOTIATION GUIDE:');
  sections.push('--------------------------------------------------------------------------');
  sections.push(`Strategy: ${data.negotiationGuide.recommendation}`);
  sections.push('');
  sections.push('Push Back:');
  data.negotiationGuide.pushBack.forEach((item) => {
    sections.push(`- ${item.clauseTitle}: ${item.rationale}`);
  });
  sections.push('');
  sections.push('Accept As-Is:');
  data.negotiationGuide.acceptAsIs.forEach((item) => {
    sections.push(`- ${item.clauseTitle}: ${item.rationale}`);
  });
  sections.push('');
  sections.push('Flag for Lawyer:');
  data.negotiationGuide.flagForLawyer.forEach((item) => {
    sections.push(`- ${item.clauseTitle}: ${item.rationale}`);
  });

  return sections.join('\n');
}
