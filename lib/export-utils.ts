export function formatDocumentMarkdown(data: DocumentAnalysis, fileName?: string): string {
  const sections: string[] = [STATUTORY_DISCLAIMER_HEADER, ''];

  sections.push(`# Document Analysis Report: ${data.documentType}`);
  if (fileName) sections.push(`**Original File:** ${fileName}`);
  sections.push(`**Identified Parties:** ${data.parties?.join(', ') || 'Not specified'}`);
  sections.push('');

  sections.push('## Executive Summary');
  sections.push(data.summary);
  sections.push('');

  sections.push('## Risk Scorecard');
  const highRisks = data.clauses.filter((c) => c.risk === 'high');
  const cautionRisks = data.clauses.filter((c) => c.risk === 'caution');
  const standardRisks = data.clauses.filter((c) => c.risk === 'standard');

  sections.push(`### 🔴 High Risk Clauses (${highRisks.length})`);
  if (highRisks.length === 0) {
    sections.push('_No high risk clauses identified._');
  } else {
    for (const c of highRisks) {
      sections.push(`#### ${c.title} (Obligation: ${c.obligation})`);
      sections.push(`**Why High Risk:** ${c.riskReason}`);
      sections.push(`**Plain-English Meaning:** ${c.simplified}`);
      sections.push('```');
      sections.push(c.originalText);
      sections.push('```');
      sections.push('');
    }
  }

  sections.push(`### 🟡 Caution Clauses (${cautionRisks.length})`);
  if (cautionRisks.length === 0) {
    sections.push('_No caution clauses identified._');
  } else {
    for (const c of cautionRisks) {
      sections.push(`#### ${c.title} (Obligation: ${c.obligation})`);
      sections.push(`**Why Caution:** ${c.riskReason}`);
      sections.push(`**Plain-English Meaning:** ${c.simplified}`);
      sections.push('```');
      sections.push(c.originalText);
      sections.push('```');
      sections.push('');
    }
  }

  sections.push(`### 🟢 Standard Clauses (${standardRisks.length})`);
  if (standardRisks.length === 0) {
    sections.push('_No standard clauses identified._');
  } else {
    for (const c of standardRisks) {
      sections.push(`#### ${c.title}`);
      sections.push(`**Plain-English Meaning:** ${c.simplified}`);
      sections.push('');
    }
  }

  sections.push('## Actionable Checklist');
  const immediate = data.checklist.filter((i) => i.timing === 'immediate');
  const beforeSigning = data.checklist.filter((i) => i.timing === 'before_signing');
  const afterSigning = data.checklist.filter((i) => i.timing === 'after_signing');

  sections.push('### Immediate Actions');
  if (immediate.length === 0) sections.push('_None_');
  for (const item of immediate) {
    sections.push(`- [ ] **[${item.actionType.toUpperCase()}]** ${item.description}`);
  }
  sections.push('');

  sections.push('### Before Signing');
  if (beforeSigning.length === 0) sections.push('_None_');
  for (const item of beforeSigning) {
    sections.push(`- [ ] **[${item.actionType.toUpperCase()}]** ${item.description}`);
  }
  sections.push('');

  sections.push('### After Signing');
  if (afterSigning.length === 0) sections.push('_None_');
  for (const item of afterSigning) {
    sections.push(`- [ ] **[${item.actionType.toUpperCase()}]** ${item.description}`);
  }
  sections.push('');

  sections.push('## Questions for Your Legal Counsel');
  if (data.lawyerQuestions?.length) {
    data.lawyerQuestions.forEach((q, idx) => {
      sections.push(`${idx + 1}. **${q.question}**`);
      sections.push(`   _Context:_ ${q.context}`);
      sections.push('');
    });
  } else {
    sections.push('_No specific lawyer questions generated._');
  }

  return sections.join('\n');
}

export function formatDocumentPlainText(data: DocumentAnalysis, fileName?: string): string {
  const sections: string[] = [STATUTORY_DISCLAIMER_HEADER, ''];

  sections.push(`DOCUMENT ANALYSIS REPORT: ${data.documentType.toUpperCase()}`);
  if (fileName) sections.push(`Original File: ${fileName}`);
  sections.push(`Identified Parties: ${data.parties?.join(', ') || 'Not specified'}`);
  sections.push('==========================================================================');
  sections.push('');

  sections.push('EXECUTIVE SUMMARY:');
  sections.push(data.summary);
  sections.push('');

  sections.push('RISK SCORECARD:');
  sections.push('--------------------------------------------------------------------------');
  for (const c of data.clauses) {
    sections.push(`[${c.risk.toUpperCase()}] ${c.title} (Obligation: ${c.obligation})`);
    sections.push(`Reason: ${c.riskReason}`);
    sections.push(`Plain-English: ${c.simplified}`);
    sections.push(`Original Excerpt: "${c.originalText.trim()}"`);
    sections.push('');
  }

  sections.push('ACTIONABLE CHECKLIST:');
  sections.push('--------------------------------------------------------------------------');
  for (const item of data.checklist) {
    sections.push(`[ ] (${item.timing.toUpperCase()} / ${item.actionType.toUpperCase()}) ${item.description}`);
  }
  sections.push('');

  sections.push('QUESTIONS FOR YOUR LEGAL COUNSEL:');
  sections.push('--------------------------------------------------------------------------');
  data.lawyerQuestions.forEach((q, idx) => {
    sections.push(`${idx + 1}. ${q.question}`);
    sections.push(`   Context: ${q.context}`);
  });

  return sections.join('\n');
}

