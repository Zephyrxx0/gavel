export function formatSituationMarkdown(data: SituationAnalysis, description?: string): string {
  const sections: string[] = [STATUTORY_DISCLAIMER_HEADER, ''];

  sections.push(`# Situation Navigation Dossier: ${data.disputeCategory.toUpperCase()}`);
  sections.push(`**Estimated Resolution Timeline:** ${data.estimatedTimeline}`);
  sections.push('');

  if (data.deadlineFlags?.length > 0) {
    sections.push('> ⚠️ **TIME-SENSITIVE DEADLINE WARNINGS:**');
    for (const flag of data.deadlineFlags) {
      sections.push(`> - ${flag}`);
    }
    sections.push('');
  }

  if (description) {
    sections.push('## User Situation Background');
    sections.push(description);
    sections.push('');
  }

  sections.push('## Situation Analysis & Overview');
  sections.push(data.summary);
  sections.push('');

  sections.push('## Your Statutory Rights & Protections');
  for (const right of data.rights) {
    sections.push(`### ${right.title}`);
    sections.push(right.explanation);
    sections.push(`*Statute / Doctrine Reference:* \`${right.statuteReference}\``);
    sections.push('');
  }

  sections.push('## Procedural Next Steps Roadmap');
  for (const step of data.roadmap) {
    const doableTag = step.doableWithoutLawyer ? '🟢 (Doable without attorney)' : '🔴 (Attorney recommended)';
    sections.push(`### [${step.urgency.toUpperCase()}] ${step.step} ${doableTag}`);
    sections.push(step.description);
    sections.push('');
  }

  sections.push('## Documents & Evidence to Gather');
  for (const doc of data.documentsToGather) {
    sections.push(`- [ ] **${doc.document}**`);
    sections.push(`  *Why needed:* ${doc.why}`);
  }
  sections.push('');

  sections.push('## When to Consult Licensed Legal Counsel');
  for (const trigger of data.whenToCallLawyer) {
    sections.push(`- ${trigger}`);
  }

  return sections.join('\n');
}

